    private void txtAmountToAddFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_txtAmountToAddFocusLost
        amount = txtAmountToAdd.getText();

        try {
            if (amount.substring(amount.length() - 2).equals("00")
                    && amount.indexOf('.') > -1) {
                amount = amount.substring(0, amount.length() - 3);
            }
        } catch (Exception e) {
        }

        if (amount.trim().length() != 0 && !amount.trim().equals("0.00")) {
            txtAmountToAdd.setText(df.format(Double.parseDouble(amount)));
        } else {
            txtAmountToAdd.setText("0.00");
            amount = "";
        }
    }//GEN-LAST:event_txtAmountToAddFocusLost

