    private void btnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmActionPerformed

        AuditFunction au = new AuditFunction();
        GeneralFunction gf = new GeneralFunction();

        String x = "";
        String y = "";

        double amount = Double.parseDouble(this.amount);

        if (moveChoice > 1) {

            for (Accounts a : GeneralFunction.list) {
                if (a.getUsername().equals(UserFunctions.username)) {
                    switch (FundAction.choice) {
                        case 1:
                            if (a.getFamilySavings() >= amount) {
                                a.setFamilySavings(a.getFamilySavings() 
                                        - amount);
                                x = "Moved " + df.format(amount) + " of Family "
                                        + "Funds to their Account";
                                y = "Retrieved money from Family Funds";
                            } else {
                                JOptionPane.showMessageDialog(null, 
                                        "Insufficient Funds.");
                            }
                            break;
                        case 2:
                            if (a.getOwnSavings() >= amount) {
                                a.setOwnSavings(a.getOwnSavings() - amount);
                                x = "Moved " + df.format(amount) + " of Own "
                                        + "Funds to their Account";
                                y = "Retrieved money from Own Funds";
                            } else {
                                JOptionPane.showMessageDialog(null, 
                                        "Insufficient Funds.");
                            }
                            break;
                    }
                    a.setBalance(a.getBalance() + amount);
                    GeneralFunction.rewrite();
                    gf.writeTransaction(UserFunctions.userID, y, "+" 
                            + df.format(amount));
                    JOptionPane.showMessageDialog(null, 
                            "Funds successfully moved.");
                    au.createAudit(UserFunctions.username, x);
                    this.dispose();
                    new CheckFunds().setVisible(true);
                    break;
                }
            }
        } else {

            for (Accounts a : GeneralFunction.list) {
                if (a.getUsername().equals(UserFunctions.username)) {
                    if (a.getBalance() >= amount) {
                        switch (FundAction.choice) {
                            case 1:
                                a.setFamilySavings(a.getFamilySavings() 
                                        + amount);
                                x = "Added "+ df.format(amount) 
                                        + " to Family Funds";
                                y = "Added money to Family Funds";
                                break;
                            case 2:
                                a.setOwnSavings(a.getOwnSavings() + amount);
                                x = "Added "+ df.format(amount) 
                                        + " to Own Funds";
                                y = "Added money to Own Funds";
                                break;
                        }
                        a.setBalance(a.getBalance() - amount);
                        GeneralFunction.rewrite();
                        au.createAudit(UserFunctions.username, x);
                        gf.writeTransaction(UserFunctions.userID, y, "-" 
                                + df.format(amount));
                        JOptionPane.showMessageDialog(null, 
                                "Funds successfully added.");
                        this.dispose();
                        new CheckFunds().setVisible(true);
                    } else {
                        JOptionPane.showMessageDialog(null, 
                                "Insufficient Balance.");
                    }
                    break;
                }
            }
        }
    }//GEN-LAST:event_btnConfirmActionPerformed

    private void txtAmountToAddKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtAmountToAddKeyTyped
        char c = evt.getKeyChar();
        if (!((c >= '0') && (c <= '9')
                || (c == KeyEvent.VK_PERIOD)
                || (c == KeyEvent.VK_BACK_SPACE)
                || (c == KeyEvent.VK_DELETE))) {
            getToolkit().beep();
            evt.consume();
        }
    }//GEN-LAST:event_txtAmountToAddKeyTyped

    private void txtAmountToAddCaretUpdate(javax.swing.event.CaretEvent evt) {//GEN-FIRST:event_txtAmountToAddCaretUpdate
        double fund;

        if (txtAmountToAdd.getText().length() > 0) {
            fund = Double.parseDouble(txtAmountToAdd.getText());
        } else {
            fund = 0;
        }
        fund = sf.getBalance(moveChoice, UserFunctions.username) - fund;

        lblMoney2.setText(df.format(fund));
    }//GEN-LAST:event_txtAmountToAddCaretUpdate

